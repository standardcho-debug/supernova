class NullCarouselRenderer:
    """Offline/test stand-in — plans without rendering, same convention as
    image_generator.NullImageGenerator (empty path = not rendered)."""

    def render(self, brief_id: str, variant: int, slide_texts: list[str]) -> dict[str, list[str]]:
        return {aspect: ["" for _ in slide_texts] for aspect in ASPECTS}


class PlaywrightCarouselRenderer:
    def __init__(self, out_dir: Path, executable_path: str | None = None):
        self._out_dir = Path(out_dir)
        self._out_dir.mkdir(parents=True, exist_ok=True)
        self._executable_path = executable_path

    def render(self, brief_id: str, variant: int, slide_texts: list[str]) -> dict[str, list[str]]:
        from playwright.sync_api import sync_playwright

        result: dict[str, list[str]] = {aspect: [] for aspect in ASPECTS}

        with sync_playwright() as p:
            browser = p.chromium.launch(executable_path=self._executable_path)
            try:
                for aspect, (width, height) in ASPECTS.items():
                    font_size = 56 if aspect == "9:16" else 48
                    page = browser.new_page(viewport={"width": width, "height": height})
                    for i, text in enumerate(slide_texts):
                        page.set_content(
                            _SLIDE_HTML.format(width=width, height=height, font_size=font_size, text=text)
                        )
                        aspect_slug = aspect.replace(":", "x")
                        out_path = (
                            self._out_dir / f"{brief_id}_v{variant}_{aspect_slug}_{i}.png"
                        )
                        page.screenshot(path=str(out_path))
                        result[aspect].append(str(out_path))
                    page.close()
            finally:
                browser.close()

        return result
